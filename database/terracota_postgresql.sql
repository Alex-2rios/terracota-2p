CREATE TABLE IF NOT EXISTS usuario_roles (
  usuario_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  rol_id smallint NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
  PRIMARY KEY (usuario_id, rol_id)
);

CREATE TABLE IF NOT EXISTS categorias (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave varchar(30) NOT NULL UNIQUE,
  nombre varchar(60) NOT NULL,
  orden smallint NOT NULL DEFAULT 0,
  activo boolean NOT NULL DEFAULT true,
  CONSTRAINT categorias_orden_valido CHECK (orden >= 0)
);

CREATE TABLE IF NOT EXISTS productos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clave varchar(60) NOT NULL UNIQUE,
  categoria_id smallint NOT NULL REFERENCES categorias(id) ON DELETE RESTRICT,
  nombre varchar(120) NOT NULL,
  descripcion varchar(250),
  precio numeric(12,2) NOT NULL,
  stock_actual integer NOT NULL DEFAULT 50,
  stock_minimo integer NOT NULL DEFAULT 15,
  disponible boolean NOT NULL DEFAULT true,
  eliminado boolean NOT NULL DEFAULT false,
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT productos_precio_valido CHECK (precio >= 0),
  CONSTRAINT productos_stock_actual_valido CHECK (stock_actual >= 0),
  CONSTRAINT productos_stock_minimo_valido CHECK (stock_minimo >= 0),
  CONSTRAINT productos_clave_formato CHECK (clave ~ '^[a-z0-9-]+$')
);

CREATE INDEX IF NOT EXISTS productos_categoria_idx ON productos(categoria_id);
CREATE INDEX IF NOT EXISTS productos_vigentes_idx ON productos(eliminado, disponible);

CREATE TABLE IF NOT EXISTS mesas (
  id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero smallint NOT NULL UNIQUE,
  capacidad smallint NOT NULL DEFAULT 4,
  estado varchar(20) NOT NULL DEFAULT 'DISPONIBLE',
  activa boolean NOT NULL DEFAULT true,
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT mesas_numero_valido CHECK (numero > 0),
  CONSTRAINT mesas_capacidad_valida CHECK (capacidad > 0),
  CONSTRAINT mesas_estado_valido CHECK (estado IN ('DISPONIBLE', 'OCUPADA', 'FUERA_SERVICIO'))
);

CREATE TABLE IF NOT EXISTS estados_pedido (
  clave varchar(20) PRIMARY KEY,
  nombre varchar(50) NOT NULL,
  orden smallint NOT NULL UNIQUE,
  es_final boolean NOT NULL DEFAULT false
);

-- ---------------------------------------------------------------- operación
CREATE TABLE IF NOT EXISTS pedidos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mesa_id smallint NOT NULL REFERENCES mesas(id) ON DELETE RESTRICT,
  mesero_id bigint NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  estado varchar(20) NOT NULL DEFAULT 'PENDIENTE' REFERENCES estados_pedido(clave),
  subtotal numeric(12,2) NOT NULL DEFAULT 0,
  tasa_impuesto numeric(5,4) NOT NULL DEFAULT 0.1600,
  impuesto numeric(12,2) NOT NULL DEFAULT 0,
  total numeric(12,2) NOT NULL DEFAULT 0,
  notas varchar(500),
  creado_en timestamptz NOT NULL DEFAULT now(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  entregado_en timestamptz,
  cerrado_en timestamptz,
  actualizado_por bigint REFERENCES usuarios(id) ON DELETE SET NULL,
  version integer NOT NULL DEFAULT 1,
  CONSTRAINT pedidos_importes_validos CHECK (subtotal >= 0 AND impuesto >= 0 AND total >= 0),
  CONSTRAINT pedidos_tasa_valida CHECK (tasa_impuesto >= 0 AND tasa_impuesto <= 1),
  CONSTRAINT pedidos_version_valida CHECK (version > 0)
);

