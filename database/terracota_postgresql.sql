CREATE OR REPLACE FUNCTION autenticar_usuario(p_usuario text, p_password text)
RETURNS TABLE(usuario_id bigint, nombre varchar, usuario varchar, roles text[])
LANGUAGE plpgsql
SET search_path = terracota, public
AS $$
DECLARE
  encontrado record;
BEGIN
  SELECT u.id, u.nombre, u.usuario,
         COALESCE(array_agg(r.clave ORDER BY r.clave)
           FILTER (WHERE r.clave IS NOT NULL), ARRAY[]::text[]) AS roles
    INTO encontrado
  FROM usuarios u
  LEFT JOIN usuario_roles ur ON ur.usuario_id = u.id
  LEFT JOIN roles r ON r.id = ur.rol_id
  WHERE u.activo AND NOT u.eliminado
    AND lower(u.usuario) = lower(btrim(p_usuario))
    AND u.password_hash = crypt(p_password, u.password_hash)
  GROUP BY u.id, u.nombre, u.usuario;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  UPDATE usuarios SET ultimo_acceso = now() WHERE id = encontrado.id;

  usuario_id := encontrado.id;
  nombre     := encontrado.nombre;
  usuario    := encontrado.usuario;
  roles      := encontrado.roles;
  RETURN NEXT;
END;
$$;

DROP FUNCTION IF EXISTS crear_pedido(smallint, bigint, jsonb, varchar, numeric);
CREATE OR REPLACE FUNCTION crear_pedido(
  p_numero_mesa integer,
  p_mesero_id bigint,
  p_items jsonb,
  p_notas varchar DEFAULT NULL,
  p_tasa_impuesto numeric DEFAULT 0.1600
)
RETURNS pedidos
LANGUAGE plpgsql
SET search_path = terracota, public
AS $$
DECLARE
  mesa_registro mesas%ROWTYPE;
  pedido_nuevo pedidos%ROWTYPE;
  faltante record;
BEGIN
  IF jsonb_typeof(p_items) <> 'array' OR jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'El pedido debe contener al menos un producto.' USING ERRCODE = 'check_violation';
  END IF;

  IF p_tasa_impuesto < 0 OR p_tasa_impuesto > 1 THEN
    RAISE EXCEPTION 'La tasa de impuesto no es válida.' USING ERRCODE = 'check_violation';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM usuarios u
    JOIN usuario_roles ur ON ur.usuario_id = u.id
    JOIN roles r ON r.id = ur.rol_id
    WHERE u.id = p_mesero_id AND u.activo AND NOT u.eliminado
      AND r.clave IN ('mesero', 'administrador')
  ) THEN
    RAISE EXCEPTION 'El usuario no tiene permisos de mesero.' USING ERRCODE = 'insufficient_privilege';
  END IF;

  -- Formato de los renglones
  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(p_items) item
    WHERE NOT (item ? 'producto_clave')
       OR NOT (item ? 'cantidad')
       OR COALESCE(item->>'cantidad', '') !~ '^[1-9][0-9]*$'
       OR (item->>'cantidad')::integer > 99
  ) THEN
    RAISE EXCEPTION 'Uno o más productos tienen un formato inválido.' USING ERRCODE = 'invalid_parameter_value';
  END IF;

  -- Mesa disponible (bloqueada hasta el fin de la transacción)
  SELECT * INTO mesa_registro FROM mesas
  WHERE numero = p_numero_mesa AND activa
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'La mesa % no existe o está inactiva.', p_numero_mesa
      USING ERRCODE = 'invalid_parameter_value';
  END IF;
  IF mesa_registro.estado <> 'DISPONIBLE' THEN
    RAISE EXCEPTION 'La mesa % ya tiene un pedido activo.', p_numero_mesa
      USING ERRCODE = 'unique_violation';
  END IF;

  -- Se bloquean los productos ANTES de validar el stock: evita que dos meseros
  -- consuman las mismas existencias al mismo tiempo.
  PERFORM 1
  FROM productos p
  WHERE p.clave IN (SELECT item->>'producto_clave' FROM jsonb_array_elements(p_items) item)
  ORDER BY p.id
  FOR UPDATE;

  IF EXISTS (
    SELECT 1 FROM jsonb_array_elements(p_items) item
    LEFT JOIN productos p
      ON p.clave = item->>'producto_clave' AND p.disponible AND NOT p.eliminado
    WHERE p.id IS NULL
  ) THEN
    RAISE EXCEPTION 'Uno o más productos no existen o no están disponibles.'
      USING ERRCODE = 'invalid_parameter_value';
  END IF;

  -- Stock suficiente (agrupado: el mismo producto puede venir en varios renglones)
  SELECT p.nombre, p.stock_actual, sub.cantidad INTO faltante
  FROM (
    SELECT item->>'producto_clave' AS clave, sum((item->>'cantidad')::integer) AS cantidad
    FROM jsonb_array_elements(p_items) item
    GROUP BY 1
  ) sub
  JOIN productos p ON p.clave = sub.clave
  WHERE p.stock_actual < sub.cantidad
  LIMIT 1;

  IF FOUND THEN
    RAISE EXCEPTION 'Stock insuficiente de "%": quedan % y se pidieron %.',
      faltante.nombre, faltante.stock_actual, faltante.cantidad
      USING ERRCODE = 'check_violation';
  END IF;

  INSERT INTO pedidos(mesa_id, mesero_id, tasa_impuesto, notas, actualizado_por)
  VALUES (mesa_registro.id, p_mesero_id, p_tasa_impuesto, NULLIF(btrim(p_notas), ''), p_mesero_id)
  RETURNING * INTO pedido_nuevo;

  INSERT INTO pedido_detalles(
    pedido_id, producto_id, nombre_producto, cantidad, precio_unitario, observacion
  )
  SELECT pedido_nuevo.id, p.id, p.nombre, (item->>'cantidad')::integer, p.precio,
         NULLIF(btrim(item->>'observacion'), '')
  FROM jsonb_array_elements(p_items) item
  JOIN productos p ON p.clave = item->>'producto_clave';

  UPDATE productos p
     SET stock_actual = p.stock_actual - sub.cantidad
  FROM (
    SELECT item->>'producto_clave' AS clave, sum((item->>'cantidad')::integer) AS cantidad
    FROM jsonb_array_elements(p_items) item
    GROUP BY 1
  ) sub
  WHERE p.clave = sub.clave;

  SELECT * INTO pedido_nuevo FROM pedidos WHERE id = pedido_nuevo.id;
  RETURN pedido_nuevo;
END;
$$;

CREATE OR REPLACE FUNCTION cambiar_estado_pedido(
  p_pedido_id bigint,
  p_estado varchar,
  p_usuario_id bigint,
  p_comentario varchar DEFAULT NULL
)
RETURNS pedidos
LANGUAGE plpgsql
SET search_path = terracota, public
AS $$
DECLARE
  estado_destino varchar(20) := upper(btrim(p_estado));
  estado_actual varchar(20);
  resultado pedidos%ROWTYPE;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM usuarios WHERE id = p_usuario_id AND activo AND NOT eliminado) THEN
    RAISE EXCEPTION 'Usuario inválido o inactivo.' USING ERRCODE = 'insufficient_privilege';
  END IF;

  SELECT estado INTO estado_actual FROM pedidos WHERE id = p_pedido_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'El pedido % no existe.', p_pedido_id USING ERRCODE = 'no_data_found';
  END IF;

  IF estado_actual = estado_destino THEN
    RAISE EXCEPTION 'El pedido ya se encuentra en estado %.', estado_destino
      USING ERRCODE = 'check_violation';
  END IF;

  -- Al cancelar se devuelven las existencias al inventario.
  --
  -- Se agrupa por producto ANTES de sumar: en `UPDATE ... FROM`, si la tabla
  -- de origen tiene varias filas que casan con la misma fila destino,
  -- PostgreSQL aplica UNA sola y descarta el resto. Un pedido puede traer el
  -- mismo producto en dos renglones (por ejemplo con observaciones distintas),
  -- y sin agrupar se devolvería sólo uno de ellos: el inventario quedaría corto.
  IF estado_destino = 'CANCELADO' THEN
    UPDATE productos p
       SET stock_actual = p.stock_actual + sub.cantidad
    FROM (
      SELECT producto_id, sum(cantidad) AS cantidad
        FROM pedido_detalles
       WHERE pedido_id = p_pedido_id
       GROUP BY producto_id
    ) sub
    WHERE p.id = sub.producto_id;
  END IF;

  UPDATE pedidos
     SET estado = estado_destino, actualizado_por = p_usuario_id
   WHERE id = p_pedido_id
  RETURNING * INTO resultado;

  -- El trigger de historial ya insertó el renglón del cambio: se le adjunta el
  -- comentario. Sólo se toca ese renglón, nunca uno anterior.
  IF NULLIF(btrim(p_comentario), '') IS NOT NULL THEN
    UPDATE pedido_estados_historial
       SET comentario = left(btrim(p_comentario), 250)
     WHERE id = (
       SELECT id FROM pedido_estados_historial
       WHERE pedido_id = p_pedido_id AND estado_nuevo = estado_destino
       ORDER BY id DESC LIMIT 1
     );
  END IF;

  RETURN resultado;
END;
$$;

CREATE OR REPLACE FUNCTION registrar_pago(
  p_pedido_id bigint,
  p_cajero_id bigint,
  p_metodo varchar,
  p_monto_recibido numeric DEFAULT NULL,
  p_referencia varchar DEFAULT NULL
)
RETURNS TABLE(ticket_id bigint, folio varchar, total numeric, cambio numeric)
LANGUAGE plpgsql
SET search_path = terracota, public
AS $$
DECLARE
  pedido_registro pedidos%ROWTYPE;
  pago_id_nuevo bigint;
  ticket_id_nuevo bigint;
  folio_nuevo varchar(12);
  metodo_normalizado varchar(20) := upper(btrim(p_metodo));
  recibido numeric(12,2);
  cambio_calculado numeric(12,2);
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM usuarios u
    JOIN usuario_roles ur ON ur.usuario_id = u.id
    JOIN roles r ON r.id = ur.rol_id
    WHERE u.id = p_cajero_id AND u.activo AND NOT u.eliminado
      AND r.clave IN ('caja', 'administrador')
  ) THEN
    RAISE EXCEPTION 'El usuario no tiene permisos de caja.' USING ERRCODE = 'insufficient_privilege';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM metodos_pago WHERE clave = metodo_normalizado AND activo) THEN
    RAISE EXCEPTION 'Método de pago inválido.' USING ERRCODE = 'invalid_parameter_value';
  END IF;

  SELECT * INTO pedido_registro FROM pedidos WHERE id = p_pedido_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'El pedido % no existe.', p_pedido_id USING ERRCODE = 'no_data_found';
  END IF;
  IF pedido_registro.estado <> 'ENTREGADO' THEN
    RAISE EXCEPTION 'El pedido debe estar ENTREGADO antes de cobrar. Estado actual: %.',
      pedido_registro.estado USING ERRCODE = 'check_violation';
  END IF;
  IF pedido_registro.total <= 0 THEN
    RAISE EXCEPTION 'El pedido no tiene un total válido.' USING ERRCODE = 'check_violation';
  END IF;

  recibido := COALESCE(p_monto_recibido, pedido_registro.total);
  IF recibido < pedido_registro.total THEN
    RAISE EXCEPTION 'El monto recibido es insuficiente: faltan %.',
      to_char(pedido_registro.total - recibido, 'FM999999990.00')
      USING ERRCODE = 'check_violation';
  END IF;

  cambio_calculado := CASE
    WHEN metodo_normalizado = 'EFECTIVO' THEN recibido - pedido_registro.total
    ELSE 0
  END;

  INSERT INTO pagos(pedido_id, cajero_id, metodo, total, monto_recibido, cambio, referencia)
  VALUES (
    pedido_registro.id, p_cajero_id, metodo_normalizado, pedido_registro.total,
    CASE WHEN metodo_normalizado = 'EFECTIVO' THEN recibido ELSE pedido_registro.total END,
    cambio_calculado, NULLIF(btrim(p_referencia), '')
  ) RETURNING id INTO pago_id_nuevo;

  INSERT INTO tickets(pago_id) VALUES (pago_id_nuevo)
  RETURNING id, tickets.folio INTO ticket_id_nuevo, folio_nuevo;

  UPDATE pedidos SET estado = 'PAGADO', actualizado_por = p_cajero_id
  WHERE id = pedido_registro.id;

  RETURN QUERY SELECT ticket_id_nuevo, folio_nuevo, pedido_registro.total, cambio_calculado;
END;
$$;

