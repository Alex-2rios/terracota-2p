CREATE OR REPLACE VIEW vista_pedidos_operativos AS
SELECT
  p.id,
  m.numero AS mesa,
  p.mesero_id,
  u.nombre AS mesero,
  p.estado,
  p.subtotal,
  p.impuesto,
  p.total,
  p.notas,
  p.creado_en,
  p.entregado_en,
  COALESCE(sum(pd.cantidad), 0)::integer AS cantidad_productos,
  COALESCE(
    jsonb_agg(jsonb_build_object(
      'producto_id', pd.producto_id,
      'nombre', pd.nombre_producto,
      'cantidad', pd.cantidad,
      'precio', pd.precio_unitario,
      'importe', pd.importe,
      'observacion', pd.observacion
    ) ORDER BY pd.id) FILTER (WHERE pd.id IS NOT NULL),
    '[]'::jsonb
  ) AS items
FROM pedidos p
JOIN mesas m ON m.id = p.mesa_id
JOIN usuarios u ON u.id = p.mesero_id
LEFT JOIN pedido_detalles pd ON pd.pedido_id = p.id
GROUP BY p.id, m.numero, u.nombre;

CREATE OR REPLACE VIEW vista_tickets AS
SELECT
  t.id,
  t.folio,
  t.emitido_en,
  p.id AS pedido_id,
  m.numero AS mesa,
  pg.metodo,
  pg.total,
  pg.monto_recibido,
  pg.cambio,
  c.nombre AS cajero,
  COALESCE(
    jsonb_agg(jsonb_build_object(
      'nombre', pd.nombre_producto,
      'cantidad', pd.cantidad,
      'precio', pd.precio_unitario,
      'importe', pd.importe
    ) ORDER BY pd.id) FILTER (WHERE pd.id IS NOT NULL),
    '[]'::jsonb
  ) AS items
FROM tickets t
JOIN pagos pg ON pg.id = t.pago_id
JOIN pedidos p ON p.id = pg.pedido_id
JOIN mesas m ON m.id = p.mesa_id
JOIN usuarios c ON c.id = pg.cajero_id
LEFT JOIN pedido_detalles pd ON pd.pedido_id = p.id
GROUP BY t.id, p.id, m.numero, pg.id, c.nombre;

CREATE OR REPLACE VIEW vista_ventas_diarias AS
SELECT
  (pg.creado_en AT TIME ZONE 'America/Mexico_City')::date AS fecha,
  count(*)::integer AS pagos,
  sum(pg.total)::numeric(14,2) AS total,
  COALESCE(sum(pg.total) FILTER (WHERE pg.metodo = 'EFECTIVO'), 0)::numeric(14,2) AS efectivo,
  COALESCE(sum(pg.total) FILTER (WHERE pg.metodo = 'TARJETA'), 0)::numeric(14,2) AS tarjeta,
  COALESCE(sum(pg.total) FILTER (WHERE pg.metodo = 'TRANSFERENCIA'), 0)::numeric(14,2) AS transferencia
FROM pagos pg
GROUP BY (pg.creado_en AT TIME ZONE 'America/Mexico_City')::date;

CREATE OR REPLACE VIEW vista_inventario AS
SELECT
  p.id,
  p.clave,
  p.nombre,
  p.descripcion,
  c.clave AS categoria_clave,
  c.nombre AS categoria,
  p.precio,
  p.stock_actual,
  p.stock_minimo,
  p.disponible,
  p.eliminado,
  CASE
    WHEN p.eliminado THEN 'ELIMINADO'
    WHEN NOT p.disponible THEN 'NO_DISPONIBLE'
    WHEN p.stock_actual = 0 THEN 'AGOTADO'
    WHEN p.stock_actual <= p.stock_minimo THEN 'BAJO'
    ELSE 'DISPONIBLE'
  END AS estado,
  -- En cuántos pedidos sin cerrar aparece. Mientras sea mayor que cero el
  -- producto no puede darse de baja: se rompería un pedido en curso.
  (SELECT count(*)
     FROM pedido_detalles pd
     JOIN pedidos pe ON pe.id = pd.pedido_id
    WHERE pd.producto_id = p.id
      AND pe.estado IN ('PENDIENTE', 'PREPARANDO', 'LISTO', 'ENTREGADO')
  )::integer AS en_pedidos_activos
FROM productos p
JOIN categorias c ON c.id = p.categoria_id;

CREATE OR REPLACE VIEW vista_usuarios AS
SELECT
  u.id,
  u.nombre,
  u.usuario,
  u.activo,
  u.eliminado,
  u.creado_en,
  u.actualizado_en,
  u.ultimo_acceso,
  COALESCE(array_agg(r.clave ORDER BY r.clave)
    FILTER (WHERE r.clave IS NOT NULL), ARRAY[]::varchar[]) AS roles,
  COALESCE(array_agg(r.nombre ORDER BY r.clave)
    FILTER (WHERE r.nombre IS NOT NULL), ARRAY[]::varchar[]) AS roles_nombre
FROM usuarios u
LEFT JOIN usuario_roles ur ON ur.usuario_id = u.id
LEFT JOIN roles r ON r.id = ur.rol_id
GROUP BY u.id;

COMMIT;
