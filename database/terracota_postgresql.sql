  observacion varchar(250),
  importe numeric(12,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
  CONSTRAINT pedido_detalles_cantidad_valida CHECK (cantidad BETWEEN 1 AND 99),
  CONSTRAINT pedido_detalles_precio_valido CHECK (precio_unitario >= 0)
